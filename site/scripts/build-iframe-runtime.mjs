/**
 * build-iframe-runtime.mjs — build the Playground's preview-app bundle.
 *
 * One self-contained ESM bundle (`site/public/iframe/iframe-app.<hash>.js` +
 * `.css`) that has Preact and the whole Anta library baked in: it registers the
 * custom elements, and seeds `window.__demo_modules__` from ITS OWN Anta/Preact
 * instances. The sandbox bundler compiles the (TS→JS) demo code with a tiny shim
 * that reads those globals, so the demo runs against the iframe's own Anta +
 * Preact — one Preact instance, and Anta's CSS (bundled here, class names
 * matching the JS) lives in the iframe. The iframe (`about:srcdoc`, its own
 * customElements registry) loads this once; it's content-hash cache-busted.
 *
 * We use Node esbuild (via Astro/Vite) so it runs at native speed in `docs:`.
 */
import { build } from 'esbuild'
import { writeFile, mkdir, readdir, unlink } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'

const root = new URL('../..', import.meta.url)
const distBundle = fileURLToPath(new URL('dist/bundle.js', root))
const distBundleCss = fileURLToPath(new URL('dist/bundle.css', root))
const iframeDir = fileURLToPath(new URL('site/public/iframe', root))
const manifestFile = fileURLToPath(new URL('site/src/generated/iframe-assets.ts', root))
// Bare specifiers (`preact`) resolve from the site's node_modules.
const siteDir = fileURLToPath(new URL('..', import.meta.url))
const require = createRequire(import.meta.url)
// Anta's generated JSX runtime imports `react`. Resolve the Preact compatibility
// entries to absolute files: an alias to bare `preact/compat` would otherwise
// resolve from `dist/`, where pnpm intentionally has no direct Preact link.
const preactCompat = require.resolve('preact/compat')
const preactJsxRuntime = require.resolve('preact/jsx-runtime')

await mkdir(iframeDir, { recursive: true })

// Entry: pull in the same full Anta bundle and stylesheet as the docs shell, then
// publish everything the demo shim needs onto `window.__demo_modules__`.
const entry = `
import ${JSON.stringify(distBundleCss)};
import * as anta from ${JSON.stringify(distBundle)};
import * as preact from 'preact';
import * as preactHooks from 'preact/hooks';
import * as plot from '@antadesign/plot';
import * as plotReact from '@antadesign/plot/react';
import '@antadesign/plot/plot.css';
if (typeof window !== 'undefined') {
  // Unmounting through THIS Preact instance is what runs the demo's effect
  // cleanups (plot listeners, tooltip portals) before the root is replaced.
  window.__demo_unmount__ = () => preact.render(null, document.getElementById('root'));
  window.__demo_modules__ = Object.assign(window.__demo_modules__ || {}, {
    '@antadesign/plot': plot,
    '@antadesign/plot/react': plotReact,
    '@antadesign/plot/plot.css': {},
    '@antadesign/anta': anta,
    '@antadesign/anta/elements': {},
    'preact': preact,
    'preact/hooks': preactHooks,
  });
}
`

const out = await build({
  stdin: { contents: entry, resolveDir: siteDir, loader: 'js' },
  outfile: `${iframeDir}/iframe-app.js`,
  bundle: true,
  format: 'esm',
  target: 'es2020',
  logLevel: 'silent',
  write: false,
  // Anta's generated JSX runtime and Plot's React host both resolve `react` —
  // map it to Preact's compat so the preview, the Anta wrappers, and Plot share
  // one Preact instance. Absolute files: an alias to bare `preact/compat` would
  // resolve from `dist/`, where pnpm intentionally has no direct Preact link.
  alias: {
    react: preactCompat,
    'react-dom': preactCompat,
    'react/jsx-runtime': preactJsxRuntime,
  },
  loader: { '.svg': 'text' },
})

// Write the JS + the sibling CSS esbuild bundles (module-class names hashed
// consistently across both), content-hashed for cache-busting.
const manifest = {}
const emittedFiles = new Set()
for (const f of out.outputFiles) {
  const ext = f.path.endsWith('.css') ? 'css' : 'js'
  const hash = createHash('sha256').update(f.contents).digest('hex').slice(0, 8)
  const file = `iframe-app.${hash}.${ext}`
  await writeFile(`${iframeDir}/${file}`, f.contents)
  emittedFiles.add(file)
  manifest[ext] = file
}

await writeFile(
  manifestFile,
  `// Auto-generated by build-iframe-runtime.mjs. Do not edit.\n` +
  `export const IFRAME_ASSETS = ${JSON.stringify(manifest, null, 2)} as const\n`,
)

// The manifest now points to the freshly written files, so old content-hashed
// siblings are safe to remove. Without this, every docs build permanently
// accumulates another pair of preview bundles in the deploy artifact.
const staleFiles = (await readdir(iframeDir)).filter(
  (file) => /^iframe-app\.[a-f0-9]{8}\.(?:css|js)$/.test(file) && !emittedFiles.has(file),
)
await Promise.all(staleFiles.map((file) => unlink(`${iframeDir}/${file}`)))
if (staleFiles.length) console.log(`removed ${staleFiles.length} stale preview assets`)

console.log('built preview app:', manifest)
