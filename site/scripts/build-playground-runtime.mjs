/**
 * build-playground-runtime.mjs — build the docs Playground editor runtimes.
 *
 * Astro's dev server deliberately serves source modules one at a time. That is
 * useful while editing an island, but loading the Playground that way makes
 * Monaco, Shiki, and esbuild-wasm appear as hundreds of network requests.
 *
 * The changing Playground app is one bundle and stylesheet. Monaco (including
 * inline workers), Shiki, and the compiler are separate ESM bundles: each has
 * a content hash and can stay in the browser cache while the Playground code
 * changes. The resulting graph is a few predictable requests, not Vite's
 * source-module graph.
 */
import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { createRequire } from 'node:module'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = new URL('../..', import.meta.url)
const siteDir = fileURLToPath(new URL('..', import.meta.url))
const runtimeDir = fileURLToPath(new URL('site/public/playground', root))
const manifestFile = fileURLToPath(new URL('site/src/generated/playground-assets.ts', root))

const require = createRequire(import.meta.url)
const astroRequire = createRequire(require.resolve('astro/package.json'))
const { build } = await import(pathToFileURL(astroRequire.resolve('vite')).href)
const preactCompat = require.resolve('preact/compat')
const preactJsxRuntime = require.resolve('preact/jsx-runtime')

const resolveEntry = (file) => fileURLToPath(new URL(file, root))

await mkdir(runtimeDir, { recursive: true })

const sharedConfig = {
  configFile: false,
  root: siteDir,
  logLevel: 'error',
  resolve: {
    alias: {
      // Anta's JSX wrappers target React. The docs use Preact compat, and each
      // static bundle must use that same runtime.
      react: preactCompat,
      'react-dom': preactCompat,
      'react/jsx-runtime': preactJsxRuntime,
    },
  },
  esbuild: {
    jsx: 'automatic',
    jsxImportSource: 'preact',
  },
}

async function buildRuntime({ entry, name, format, includeCss = false }) {
  const result = await build({
    ...sharedConfig,
    build: {
      emptyOutDir: false,
      write: false,
      cssCodeSplit: false,
      lib: {
        entry,
        name: 'AntaPlayground',
        formats: [format],
        fileName: () => `${name}.js`,
        cssFileName: name,
      },
      rollupOptions: {
        output: {
          inlineDynamicImports: true,
        },
      },
    },
  })

  const output = Array.isArray(result) ? result.flatMap((item) => item.output) : result.output
  const chunks = output.filter((file) => file.type === 'chunk')
  const css = output.filter((file) => file.type === 'asset' && file.fileName.endsWith('.css'))

  if (chunks.length !== 1 || (includeCss && css.length !== 1) || (!includeCss && css.length !== 0)) {
    throw new Error(
      `Expected ${name} to emit one JavaScript${includeCss ? ' and one CSS' : ''} bundle; got ${output.map((file) => file.fileName).join(', ')}.`,
    )
  }

  const writeAsset = async (contents, ext) => {
    const hash = createHash('sha256').update(contents).digest('hex').slice(0, 8)
    const file = `${name}.${hash}.${ext}`
    await writeFile(`${runtimeDir}/${file}`, contents)
    return file
  }

  return {
    js: await writeAsset(chunks[0].code, 'js'),
    ...(includeCss ? { css: await writeAsset(css[0].source, 'css') } : {}),
  }
}

const monaco = await buildRuntime({
  entry: resolveEntry('site/src/components/playground-monaco.ts'),
  name: 'playground-monaco',
  format: 'es',
  includeCss: true,
})
const vendors = {
  monaco: monaco.js,
  monacoCss: monaco.css,
  shiki: (await buildRuntime({
    entry: resolveEntry('site/src/components/playground-shiki.ts'),
    name: 'playground-shiki',
    format: 'es',
  })).js,
  compiler: (await buildRuntime({
    entry: resolveEntry('site/src/components/playground-esbuild.ts'),
    name: 'playground-compiler',
    format: 'es',
  })).js,
}

// The app imports this file while it is built. Vendor names are stable at this
// point; overwrite it with the final app names after the build completes.
async function writeManifest(assets) {
  await writeFile(
    manifestFile,
    `// Auto-generated by build-playground-runtime.mjs. Do not edit.\n` +
      `export const PLAYGROUND_ASSETS = ${JSON.stringify(assets, null, 2)} as const\n`,
  )
}

await writeManifest({ js: '', css: '', ...vendors })

const app = await buildRuntime({
  entry: resolveEntry('site/src/components/playground-runtime.tsx'),
  name: 'playground-app',
  format: 'iife',
  includeCss: true,
})
const assets = { ...app, ...vendors }
await writeManifest(assets)

const emittedFiles = new Set(Object.values(assets))
const staleFiles = (await readdir(runtimeDir)).filter(
  (file) => /^playground-(?:app|monaco|shiki|compiler)\.[a-f0-9]{8}\.(?:css|js)$/.test(file) && !emittedFiles.has(file),
)
await Promise.all(staleFiles.map((file) => unlink(`${runtimeDir}/${file}`)))
if (staleFiles.length) console.log(`removed ${staleFiles.length} stale Playground assets`)

console.log('built Playground runtimes:', assets)
